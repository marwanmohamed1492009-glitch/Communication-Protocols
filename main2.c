#define F_CPU 16000000UL
#include <avr/io.h>
#include "SPI_1.h"
#include "BIT_MATH.h"

int main(void) {
    /* ????? ??????? ?? Slave */
SPI_slaveInit();
    /* ??? ??? ????? (????? PD0) ???? ????? ????? */
    SET_BIT(DDRD, PD0);
    CLR_BIT(PORTD, PD0);

    uint8_t receivedData = 0;

    while (1) {
        /* ?????? ?????? ?????? ??? SPI */
        receivedData = SPI_receive();

        /* ?????? ?? ?????? ???? ???? ?? ?????? ???????? ???????? */
        if (receivedData == 1) {
            /* ??? ???? ????? (???? ?? ?????? ????? ?? ?????) */
            TOGGLE_BIT(PORTD, PD0);
        }
    }

    return 0;
}